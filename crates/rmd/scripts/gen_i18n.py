"""Generate src/i18n_table.rs from the Python translation table.

Run from the repository root:  uv run python crates/rmd/scripts/gen_i18n.py
"""
import sys
from pathlib import Path

sys.path.insert(0, "src")
from schedule_management.i18n import ZH_TRANSLATIONS  # noqa: E402


def rust_str(value: str) -> str:
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main() -> None:
    entries = sorted(ZH_TRANSLATIONS.items(), key=lambda kv: kv[0].encode("utf-8"))
    lines = [
        "// @generated by scripts/gen_i18n.py from the original Python translation table.",
        "// English source text -> Simplified Chinese. Sorted by UTF-8 bytes for binary search.",
        "",
        "pub(crate) static ZH_TRANSLATIONS: &[(&str, &str)] = &[",
    ]
    for key, value in entries:
        lines.append(f"    ({rust_str(key)}, {rust_str(value)}),")
    lines.append("];")
    Path("crates/rmd/src/i18n_table.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(entries)} entries")


if __name__ == "__main__":
    main()
